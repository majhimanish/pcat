"""v5 driver (spec docs/specs/v5-open-source-simulation.md).

    python scripts/v5.py clone          # check out the pinned apps into .bench/apps/<app>
    python scripts/v5.py mine           # pcat mine each app -> experiments/v5/mining/<app>/

Later parts add subcommands. Logic lives in src/pcat/v5.py.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
V5 = ROOT / "experiments" / "v5"
APPS_DIR = ROOT / ".bench" / "apps"


def apps() -> dict:
    return yaml.safe_load((V5 / "apps.yaml").read_text())


def cmd_clone(args) -> int:
    for name, app in apps()["apps"].items():
        dest = APPS_DIR / name
        if not dest.exists():
            subprocess.run(["git", "clone", "-q", "--depth", "1", "--branch", str(app["tag"]), app["repo"],
                            str(dest)], check=True)
        head = subprocess.run(["git", "-C", str(dest), "rev-parse", "HEAD"], capture_output=True,
                              text=True, check=True).stdout.strip()
        if head != app["commit"]:
            sys.exit(f"{name}: checked out {head}, expected {app['commit']}")
        print(f"{name}: {app['tag']} {head}")
    return 0


def cmd_mine(args) -> int:
    pcat = str(Path(sys.executable).parent / "pcat")
    excludes = [x for e in apps()["mining_excludes"] for x in ("--exclude", e)]
    for name in apps()["apps"]:
        out = V5 / "mining" / name
        subprocess.run([pcat, "mine", ".", "--out", str(out), "--jobs", str(args.jobs), "--cache-dir",
                        str(ROOT / ".bench" / "mine-cache"), *excludes], cwd=APPS_DIR / name, check=True)
    write_mining_summary()
    return 0


def write_mining_summary() -> None:
    import json

    lines = ["# v5 mining summary", "", "Generated by `python scripts/v5.py mine` from `<app>/report.json`.", "",
             "| App | Files mined | Functions found | Functions mined | Function clusters | Fragment clusters |",
             "|---|---|---|---|---|---|"]
    tops = []
    for name in apps()["apps"]:
        r = json.loads((V5 / "mining" / name / "report.json").read_text())
        st = r["stats"]
        lines.append(f"| {name} | {st['files_mined']} | {st['functions_found']} | {st['functions_mined']} | "
                     f"{st['function_clusters']} | {st['fragment_clusters']} |")
        tops.append(f"\n## {name}: top clusters\n")
        for c in r["function_clusters"][:5]:
            names = ", ".join(sorted({m["qualname"].split(".")[-1] for m in c["members"]})[:4])
            files = ", ".join(sorted({m["path"] for m in c["members"]})[:3])
            tops.append(f"- function `{c['id']}` x{len(c['members'])}: {names} ({files})")
        for c in r["fragment_clusters"][:3]:
            files = ", ".join(sorted({m["path"] for m in c["members"]})[:3])
            tops.append(f"- fragment `{c['id']}` x{len(c['members'])} ({files})")
    (V5 / "mining" / "summary.md").write_text("\n".join(lines + tops) + "\n")


def cmd_references(args) -> int:
    from pcat import v5

    out = V5 / "references"
    for task in v5.load_tasks(V5 / "tasks.yaml"):
        source = (APPS_DIR / task.app / task.file).read_text(encoding="utf-8")
        new, refs = v5.remove_functions(source, task.remove)
        ref = v5.reference_source(source, task.remove)
        dest = out / task.app / f"{task.id}.py"
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(ref, encoding="utf-8")
        print(f"{task.app}/{task.id}: removed {', '.join(task.remove)} from {task.file} "
              f"({len(source.splitlines()) - len(new.splitlines())} lines)")
    return 0


def cmd_requests(args) -> int:
    import datetime as dt
    import shutil
    import tempfile
    from concurrent.futures import ThreadPoolExecutor

    from pcat import evaluation, v5, variance

    target = V5 / "requests.json"
    previous = {}
    if target.exists():
        if not args.resume:
            sys.exit("experiments/v5/requests.json exists; it must not be regenerated (--resume fills gaps)")
        previous = {r["id"]: r for r in json.loads(target.read_text())["items"] if r["request"]}
    jobs = v5.request_jobs(v5.load_tasks(V5 / "tasks.yaml"),
                           yaml.safe_load((V5 / "retrieval_needs.yaml").read_text()))
    todo = [j for j in jobs if j["id"] not in previous]

    def run(job):
        workdir = Path(tempfile.mkdtemp(prefix="pcat-v5-req-"))
        try:
            gen, attempts, error = variance.generate_with_retries(variance.CliGenerator(args.model, workdir),
                                                                  job["prompt"])
        finally:
            shutil.rmtree(workdir, ignore_errors=True)
        text = evaluation.clean_request(gen.text) if gen else None
        return {**job, "request": text, "words": v5.word_count(text) if text else None,
                "raw_response": gen.text if gen else None, "model": gen.model if gen else None,
                "attempts": attempts, "error": error,
                "timestamp": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds")}

    print(f"generating {len(todo)} of {len(jobs)} brief requests ({args.model})")
    with ThreadPoolExecutor(max_workers=args.jobs) as pool:
        fresh = {r["id"]: r for r in pool.map(run, todo)}
    items = [previous.get(j["id"]) or fresh[j["id"]] for j in jobs]
    v5.write_json(target, {"model": args.model, "prompt_template": v5.REQUEST_PROMPT, "items": items})
    failed = [r["id"] for r in items if not r["request"]]
    print(f"wrote {target.relative_to(ROOT)}: {len(items) - len(failed)} ok, {len(failed)} failed {failed[:5]}")
    return 0


def cmd_retrieval(args) -> int:
    from pcat import catalog as cat
    from pcat import evaluation, search, v5

    requests = json.loads((V5 / "requests.json").read_text())["items"]
    generic = {p.meta.id for p in cat.load_catalog(ROOT)}
    out: dict = {"threshold": search.MATCH_THRESHOLD, "apps": {}}
    for app in apps()["apps"]:
        root = V5 / "catalogs" / app
        index = search.SearchIndex.from_root(root)
        house = {e["id"] for e in index.entries} - generic
        items = []
        for r in requests:
            if r["app"] != app:
                continue
            ranked = [(h.id, h.score) for h in index.rank(r["request"])]
            items.append({"task": r["set"], "id": r["id"], "request": r["request"], "expected": r["expected"],
                          "ranked": ranked[:5], "words": r["words"]})
        result = {}
        for name, subset in (("tasks", [i for i in items if i["task"] == "task"]),
                             ("extra", [i for i in items if i["task"] == "extra"]), ("all", items)):
            m = evaluation.retrieval_metrics(subset, search.MATCH_THRESHOLD)
            result[name] = {k: m[k] for k in ("positives", "negatives", "top1", "top3", "top1_ignoring_threshold",
                                              "false_match_rate", "false_matches")}
        result["misses"] = [{"id": i["id"], "request": i["request"], "expected": i["expected"],
                             "ranked": [[p, round(s, 3)] for p, s in i["ranked"][:3]]}
                            for i in items if i["expected"] and not (
                                i["ranked"] and i["ranked"][0][0] == i["expected"]
                                and i["ranked"][0][1] >= search.MATCH_THRESHOLD)]
        result["overlap"] = v5.overlap_summary(items, house, search.MATCH_THRESHOLD)
        result["short_queries"] = v5.below_threshold(items, search.MATCH_THRESHOLD)
        result["catalog"] = {"house": len(house), "generic": len(index.entries) - len(house)}
        result["items"] = items
        out["apps"][app] = result
        a = result["all"]
        print(f"{app}: top1 {a['top1']:.2f} top3 {a['top3']:.2f} (ignoring threshold {a['top1_ignoring_threshold']:.2f}) "
              f"false {a['false_match_rate']:.2f}; overlap {result['overlap']['both_above_threshold']} "
              f"(house first {result['overlap']['house_first']}, expected first {result['overlap']['first_is_expected']}); "
              f"below threshold {result['short_queries']['ranked_first_but_below_threshold']}")
    v5.write_json(V5 / "retrieval.json", out)
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="v5 evaluation")
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("clone")
    m = sub.add_parser("mine")
    m.add_argument("--jobs", type=int, default=6)
    sub.add_parser("mining-summary")
    sub.add_parser("references")
    sub.add_parser("retrieval")
    rq = sub.add_parser("requests")
    rq.add_argument("--resume", action="store_true")
    rq.add_argument("--jobs", type=int, default=8)
    rq.add_argument("--model", default="claude-sonnet-5-5")
    args = parser.parse_args()
    return {"clone": cmd_clone, "mine": cmd_mine,
            "mining-summary": lambda a: write_mining_summary() or 0, "references": cmd_references,
            "requests": cmd_requests, "retrieval": cmd_retrieval}[args.command](args)


if __name__ == "__main__":
    raise SystemExit(main())
