"""Mine repositories for repeated code shapes (spec docs/specs/v2-miner.md).

Pipeline: discover files -> analyze each file (cached, optionally in a process
pool) -> filter -> cluster by shape fingerprint -> catalog coverage -> report.

`report.json` must be byte-identical across runs on the same inputs, so nothing
here depends on timestamps, absolute paths, iteration order of sets/dicts, the
number of worker processes or cache state.
"""

from __future__ import annotations

import ast
import copy
import fnmatch
import hashlib
import json
import os
import subprocess
from concurrent.futures import ProcessPoolExecutor
from dataclasses import asdict, dataclass, field
from pathlib import Path

from pcat import canonical, shape
from pcat.errors import PcatError

# Version of the per-file analysis format stored in the cache. Bump whenever
# analyze_file's output changes.
MINER_VERSION = 1
REPORT_JSON = "report.json"
REPORT_HTML = "report.html"
DEFAULT_CACHE_DIR = ".pcat-cache"

DEFAULT_SKIP_DIRS = (
    ".git",
    ".venv",
    "venv",
    "site-packages",
    "node_modules",
    "build",
    "dist",
    "vendor",
    "third_party",
    "migrations",
    "__pycache__",
)
TEST_DIRS = ("tests", "test")
GENERATED_MARKERS = ("generated by", "do not edit")
TRIVIAL_BODY_TYPES = (ast.Pass, ast.Return, ast.Raise)
_FUNC_TYPES = (ast.FunctionDef, ast.AsyncFunctionDef)


@dataclass(frozen=True)
class MineSettings:
    """Every option that affects report.json (jobs and caching do not)."""

    min_nodes: int = 20
    min_occurrences: int = 3
    min_fragment_nodes: int = 25
    include_tests: bool = False
    include_generated: bool = False
    include_trivial: bool = False
    skip_dirs: bool = True
    excludes: tuple[str, ...] = ()
    fragments: bool = True

    def to_report(self) -> dict:
        data = asdict(self)
        data["excludes"] = list(self.excludes)
        return data

    @property
    def analysis_key(self) -> str:
        """Settings that change per-file analysis output (part of the cache key)."""
        frag = f"fr{self.min_fragment_nodes}" if self.fragments else "fr-off"
        return f"c{canonical.CANONICAL_VERSION}-s{shape.SHAPE_VERSION}-m{MINER_VERSION}-{frag}"


@dataclass
class MineResult:
    report: dict
    cache_hits: int = 0
    cache_misses: int = 0


# --------------------------------------------------------------------------- #
# Discovery and file-level filters
# --------------------------------------------------------------------------- #


@dataclass(frozen=True)
class SourceFile:
    input_index: int
    rel: str  # POSIX path relative to its input (file name for a file input)
    abs_path: str


def _is_test_path(rel: str) -> bool:
    parts = rel.split("/")
    name = parts[-1]
    if any(p in TEST_DIRS for p in parts[:-1]):
        return True
    return (
        name.startswith("test_") or name.endswith("_test.py") or name == "conftest.py"
    )


def _is_excluded(rel: str, globs: tuple[str, ...]) -> bool:
    name = rel.rsplit("/", 1)[-1]
    return any(fnmatch.fnmatchcase(rel, g) or fnmatch.fnmatchcase(name, g) for g in globs)


def discover(
    inputs: list[str], settings: MineSettings
) -> tuple[list[SourceFile], list[dict], int]:
    """Return (files to analyze, skipped file records, number of .py files seen)."""
    files: list[SourceFile] = []
    skipped: list[dict] = []
    seen = 0
    for index, raw in enumerate(inputs):
        path = Path(raw)
        if path.is_file():
            candidates = [(path.name, path)]
        elif path.is_dir():
            candidates = []
            for dirpath, dirnames, filenames in os.walk(path):
                if settings.skip_dirs:
                    dirnames[:] = [d for d in dirnames if d not in DEFAULT_SKIP_DIRS]
                dirnames.sort()
                for name in sorted(filenames):
                    if name.endswith(".py"):
                        full = Path(dirpath) / name
                        candidates.append((full.relative_to(path).as_posix(), full))
        else:
            raise PcatError(f"input {raw!r} does not exist")
        for rel, full in sorted(candidates):
            seen += 1
            reason = None
            if not settings.include_tests and _is_test_path(rel):
                reason = "test"
            elif _is_excluded(rel, settings.excludes):
                reason = "excluded"
            if reason:
                skipped.append({"input": index, "path": rel, "reason": reason, "error": None})
            else:
                files.append(SourceFile(index, rel, str(full)))
    return files, skipped, seen


def _git_info(path: str) -> dict | None:
    """Commit and exact tag when `path` is the top level of a git work tree."""
    p = Path(path)
    if not p.is_dir():
        return None

    def git(*args: str) -> str | None:
        proc = subprocess.run(["git", "-C", str(p), *args], capture_output=True, text=True)
        return proc.stdout.strip() if proc.returncode == 0 else None

    top = git("rev-parse", "--show-toplevel")
    if top is None or Path(top).resolve() != p.resolve():
        return None
    return {"commit": git("rev-parse", "HEAD"), "tag": git("describe", "--tags", "--exact-match")}


# --------------------------------------------------------------------------- #
# Per-file analysis (runs in worker processes; output is cached as JSON)
# --------------------------------------------------------------------------- #


def _is_generated(data: bytes) -> bool:
    head = data.decode("utf-8", errors="replace").splitlines()[:5]
    return any(marker in line.lower() for line in head for marker in GENERATED_MARKERS)


def _strip_docstring(body: list[ast.stmt]) -> list[ast.stmt]:
    i = 0
    while i < len(body) and canonical._is_string_expr(body[i]):
        i += 1
    return body[i:]


def mine_function(node: ast.FunctionDef) -> dict:
    """Exact and shape fingerprints of one function canonicalized on its own.

    Decorators are dropped; names the function does not define stay as they are.
    """
    clone = copy.deepcopy(node)
    clone.decorator_list = []
    source = ast.unparse(ast.Module(body=[clone], type_ignores=[]))
    result = canonical.analyze(source, clone.name)
    shape_text = shape.shape_text_from_canonical(result.text)
    func = ast.parse(shape_text).body[0]
    body = func.body
    trivial = len(body) == 1 and (
        isinstance(body[0], TRIVIAL_BODY_TYPES)
        or (
            isinstance(body[0], ast.Expr)
            and isinstance(body[0].value, ast.Constant)
            and body[0].value.value is Ellipsis
        )
    )
    return {
        "exact_fingerprint": result.fingerprint,
        "shape_fingerprint": canonical.fingerprint(shape_text),
        "shape_text": shape_text,
        "node_count": shape.node_count(func),
        "trivial": trivial,
    }


class _FunctionCollector(ast.NodeVisitor):
    """Every function definition with its qualified name and kind."""

    def __init__(self) -> None:
        self.found: list[tuple[ast.FunctionDef, str, str, bool]] = []
        self._stack: list[tuple[str, str]] = []  # (kind, name)

    def _qualname(self, name: str) -> str:
        parts = []
        for kind, outer in self._stack:
            parts.append(outer)
            if kind == "function":
                parts.append("<locals>")
        return ".".join([*parts, name])

    def visit_ClassDef(self, node: ast.ClassDef) -> None:  # noqa: N802
        self._stack.append(("class", node.name))
        self.generic_visit(node)
        self._stack.pop()

    def visit_FunctionDef(self, node) -> None:  # noqa: N802
        if not self._stack:
            kind = "function"
        elif self._stack[-1][0] == "class":
            kind = "method"
        else:
            kind = "nested"
        self.found.append((node, self._qualname(node.name), kind, False))
        self._stack.append(("function", node.name))
        self.generic_visit(node)
        self._stack.pop()

    visit_AsyncFunctionDef = visit_FunctionDef


def analyze_source(data: bytes, settings: MineSettings) -> dict:
    """Analyze one file's bytes. Pure function of (data, settings.analysis_key).

    Generated files are analyzed too and flagged; skipping them is decided by
    the caller, so the cache does not depend on --include-generated.
    """
    generated = _is_generated(data)
    try:
        tree = ast.parse(data)
    except (SyntaxError, ValueError) as exc:
        line = getattr(exc, "lineno", None)
        msg = getattr(exc, "msg", None) or str(exc)
        where = f"line {line}: " if line else ""
        return {
            "status": "parse_error",
            "generated": generated,
            "error": f"{where}{msg}",
            "functions": [],
            "fragments": [],
        }

    top_level = {id(n) for n in tree.body if isinstance(n, _FUNC_TYPES)}
    collector = _FunctionCollector()
    collector.visit(tree)
    functions = []
    fragments: list[dict] = []
    for node, qualname, kind, _ in collector.found:
        record = {
            "qualname": qualname,
            "name": node.name,
            "kind": kind,
            "top_level": id(node) in top_level,
            "async": isinstance(node, ast.AsyncFunctionDef),
            "lineno": node.lineno,
            "end_lineno": node.end_lineno,
            "decorators": [ast.unparse(d) for d in node.decorator_list],
            "error": None,
        }
        try:
            record.update(mine_function(node))
        except (PcatError, RecursionError) as exc:
            record["error"] = str(exc) or type(exc).__name__
        functions.append(record)
    return {
        "status": "ok",
        "generated": generated,
        "error": None,
        "functions": functions,
        "fragments": fragments,
    }


def _analyze_file(job: tuple[str, str | None, MineSettings]) -> tuple[str, dict, bool]:
    """Worker: (abs path, cache dir, settings) -> (file sha256, analysis, cache hit)."""
    abs_path, cache_dir, settings = job
    data = Path(abs_path).read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    cache_file = None
    if cache_dir:
        cache_file = Path(cache_dir) / f"{digest}-{settings.analysis_key}.json"
        if cache_file.is_file():
            try:
                return digest, json.loads(cache_file.read_text(encoding="utf-8")), True
            except (OSError, ValueError):
                pass  # unreadable cache entry: recompute
    analysis = analyze_source(data, settings)
    if cache_file is not None:
        cache_file.parent.mkdir(parents=True, exist_ok=True)
        tmp = cache_file.with_suffix(f".{os.getpid()}.tmp")
        tmp.write_text(json.dumps(analysis, sort_keys=True), encoding="utf-8")
        os.replace(tmp, cache_file)
    return digest, analysis, False


# --------------------------------------------------------------------------- #
# Clustering
# --------------------------------------------------------------------------- #


def _member_sort_key(m: dict) -> tuple:
    return (m["input"], m["path"], m["lineno"], m.get("col_offset", 0), m["qualname"])


def build_clusters(
    items: list[dict], prefix: str, min_occurrences: int, catalog_shapes: dict, catalog_exacts: dict
) -> list[dict]:
    """Group items (functions or fragments) by shape fingerprint."""
    by_shape: dict[str, list[dict]] = {}
    for item in items:
        by_shape.setdefault(item["shape_fingerprint"], []).append(item)

    clusters = []
    for shape_fp, group in by_shape.items():
        if len(group) < min_occurrences:
            continue
        group = sorted(group, key=_member_sort_key)
        members = []
        for i, item in enumerate(group):
            member = {k: v for k, v in item.items() if k not in _CLUSTER_LEVEL_FIELDS}
            member["index"] = i
            members.append(member)
        by_exact: dict[str, list[int]] = {}
        for m in members:
            by_exact.setdefault(m["exact_fingerprint"], []).append(m["index"])
        exact_groups = sorted(
            (
                {"exact_fingerprint": fp, "count": len(idx), "members": idx}
                for fp, idx in by_exact.items()
            ),
            key=lambda g: (-g["count"], g["members"][0]),
        )
        node_count = group[0]["node_count"]
        occurrences = len(group)
        matches = []
        for key in sorted(catalog_shapes.get(shape_fp, ())):
            exact = any(catalog_exacts.get(m["exact_fingerprint"], set()) & {key} for m in members)
            matches.append({"pattern": key, "match": "exact" if exact else "shape"})
        clusters.append(
            {
                "id": f"{prefix}-{shape_fp[:12]}",
                "shape_fingerprint": shape_fp,
                "score": (occurrences - 1) * node_count,
                "occurrences": occurrences,
                "node_count": node_count,
                "distinct_files": len({(m["input"], m["path"]) for m in members}),
                "distinct_inputs": len({m["input"] for m in members}),
                "catalog_matches": matches,
                "shape_text": group[0]["shape_text"],
                "exact_groups": exact_groups,
                "members": members,
            }
        )
    clusters.sort(key=lambda c: (-c["score"], c["id"], c["shape_fingerprint"]))
    return clusters


# Fields stored once per cluster rather than on every member.
_CLUSTER_LEVEL_FIELDS = frozenset(
    {"shape_fingerprint", "shape_text", "node_count", "trivial", "error"}
)


# --------------------------------------------------------------------------- #
# Catalog coverage
# --------------------------------------------------------------------------- #


def catalog_fingerprints(root: Path | None) -> tuple[list[str], dict, dict]:
    """(pattern keys, shape fp -> keys, exact fp -> keys) for the catalog at `root`.

    For each valid pattern: the whole pattern's canonical form and its entry
    point alone (canonicalized like a mined function).
    """
    if root is None:
        return [], {}, {}
    from pcat import catalog as cat  # local import: catalog is optional for mining

    keys: list[str] = []
    shapes: dict[str, set[str]] = {}
    exacts: dict[str, set[str]] = {}
    for pattern in cat.load_catalog(root):
        if pattern.meta is None:
            continue
        try:
            whole = cat.analyze_pattern(pattern)
            tree = ast.parse(pattern.impl_path.read_bytes())
            entry = next(
                n
                for n in tree.body
                if isinstance(n, _FUNC_TYPES) and n.name == pattern.meta.entry_point
            )
            alone = mine_function(entry)
        except (PcatError, StopIteration, SyntaxError, OSError):
            continue
        key = pattern.meta.key
        keys.append(key)
        for fp in (whole.fingerprint, alone["exact_fingerprint"]):
            exacts.setdefault(fp, set()).add(key)
        for fp in (canonical.fingerprint(shape.shape_text_from_canonical(whole.text)),
                   alone["shape_fingerprint"]):
            shapes.setdefault(fp, set()).add(key)
    return sorted(keys), shapes, exacts


def _percent(part: int, whole: int) -> float:
    return round(100.0 * part / whole, 2) if whole else 0.0


def coverage(functions: list[dict], keys: list[str], shapes: dict, exacts: dict) -> dict:
    covered: dict[str, int] = {k: 0 for k in keys}
    near: dict[str, int] = {k: 0 for k in keys}
    n_covered = n_near = 0
    for f in functions:
        exact_keys = exacts.get(f["exact_fingerprint"])
        if exact_keys:
            n_covered += 1
            for k in exact_keys:
                covered[k] += 1
            continue
        shape_keys = shapes.get(f["shape_fingerprint"])
        if shape_keys:
            n_near += 1
            for k in shape_keys:
                near[k] += 1
    total = len(functions)
    return {
        "catalog_patterns": len(keys),
        "functions": total,
        "covered": n_covered,
        "covered_percent": _percent(n_covered, total),
        "near_covered": n_near,
        "near_covered_percent": _percent(n_near, total),
        "patterns": [
            {"pattern": k, "covered": covered[k], "near_covered": near[k]} for k in keys
        ],
    }


# --------------------------------------------------------------------------- #
# Orchestration
# --------------------------------------------------------------------------- #


def _function_filter_reason(f: dict, settings: MineSettings) -> str | None:
    if f["error"] is not None:
        return "cannot_canonicalize"
    if not settings.include_trivial and f["trivial"]:
        return "trivial_body"
    if f["node_count"] < settings.min_nodes:
        return "too_small"
    return None


def mine(
    inputs: list[str],
    settings: MineSettings = MineSettings(),
    jobs: int = 1,
    cache_dir: str | None = DEFAULT_CACHE_DIR,
    catalog_root: Path | None = None,
) -> MineResult:
    files, skipped, seen = discover(inputs, settings)
    jobs_list = [(f.abs_path, cache_dir, settings) for f in files]
    if jobs > 1 and len(jobs_list) > 1:
        with ProcessPoolExecutor(max_workers=jobs) as pool:
            results = list(pool.map(_analyze_file, jobs_list, chunksize=8))
    else:
        results = [_analyze_file(job) for job in jobs_list]

    result = MineResult(report={})
    functions: list[dict] = []
    fragments: list[dict] = []
    filtered: dict[str, int] = {}
    total_functions = 0
    for source_file, (digest, analysis, hit) in zip(files, results):
        if hit:
            result.cache_hits += 1
        else:
            result.cache_misses += 1
        status = analysis["status"]
        if analysis["generated"] and not settings.include_generated:
            status = "generated"
        if status != "ok":
            skipped.append(
                {
                    "input": source_file.input_index,
                    "path": source_file.rel,
                    "reason": status,
                    "error": analysis["error"] if status == "parse_error" else None,
                }
            )
            continue
        base = {"input": source_file.input_index, "path": source_file.rel, "file_hash": digest}
        for f in analysis["functions"]:
            total_functions += 1
            reason = _function_filter_reason(f, settings)
            if reason:
                filtered[reason] = filtered.get(reason, 0) + 1
                continue
            functions.append({**base, **f})
        for fr in analysis["fragments"]:
            fragments.append({**base, **fr})

    keys, cat_shapes, cat_exacts = catalog_fingerprints(catalog_root)
    function_clusters = build_clusters(
        functions, "fn", settings.min_occurrences, cat_shapes, cat_exacts
    )
    fragment_clusters = postprocess_fragments(fragments, settings) if settings.fragments else []

    skipped.sort(key=lambda s: (s["input"], s["path"]))
    skipped_by_reason: dict[str, int] = {}
    for s in skipped:
        skipped_by_reason[s["reason"]] = skipped_by_reason.get(s["reason"], 0) + 1

    result.report = {
        "canonical_version": canonical.CANONICAL_VERSION,
        "shape_version": shape.SHAPE_VERSION,
        "settings": settings.to_report(),
        "inputs": [{"path": Path(p).as_posix(), "git": _git_info(p)} for p in inputs],
        "stats": {
            "files_seen": seen,
            "files_mined": seen - len(skipped),
            "files_skipped": dict(sorted(skipped_by_reason.items())),
            "functions_found": total_functions,
            "functions_mined": len(functions),
            "functions_filtered": dict(sorted(filtered.items())),
            "fragments_mined": len(fragments),
            "function_clusters": len(function_clusters),
            "fragment_clusters": len(fragment_clusters),
        },
        "coverage": coverage(functions, keys, cat_shapes, cat_exacts),
        "function_clusters": function_clusters,
        "fragment_clusters": fragment_clusters,
        "skipped_files": [
            {"input": s["input"], "path": s["path"], "reason": s["reason"], "error": s["error"]}
            for s in skipped
        ],
    }
    return result


def postprocess_fragments(fragments: list[dict], settings: MineSettings) -> list[dict]:
    """Fragment clusters (Part B)."""
    return []


def report_json_text(report: dict) -> str:
    return json.dumps(report, sort_keys=True, indent=2, ensure_ascii=False) + "\n"


def write_report(report: dict, out_dir: Path) -> tuple[Path, Path]:
    from pcat import report_html  # local import keeps the HTML renderer optional

    out_dir.mkdir(parents=True, exist_ok=True)
    json_path = out_dir / REPORT_JSON
    html_path = out_dir / REPORT_HTML
    text = report_json_text(report)
    with open(json_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    # HTML is rendered from the JSON text just written, so the two never disagree.
    with open(html_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(report_html.render(json.loads(text)))
    return json_path, html_path
